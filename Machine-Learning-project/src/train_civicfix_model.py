"""
============================================================
CIVICFIX — TRAIN ML MODEL FROM DATASET
============================================================
Trains on erm2-nwe9.csv and saves model to:
  frontend/src/services/ml_model_data.js

The web app will use these learned rules instead of
hardcoded keywords.

Targets learned from dataset:
  - complaint_type  → which department (agency) handles it
  - description keywords → priority prediction
  - complaint_type → status prediction (Open/In Progress/Closed)
============================================================
"""

import os
import json
import pandas as pd
import numpy as np
from collections import Counter

# ── Paths ─────────────────────────────────────────────────
BASE     = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATASET  = os.path.join(BASE, "dataset", "erm2-nwe9.csv")
OUT_JS   = os.path.join(BASE, "frontend", "src", "services", "ml_model_data.js")

print("=" * 65)
print("  CIVICFIX — TRAINING ML MODEL FROM DATASET")
print("=" * 65)
print(f"  Dataset : {DATASET}")

# ── Load ──────────────────────────────────────────────────
df = pd.read_csv(DATASET, low_memory=False, encoding_errors="replace")

# Drop unnamed columns
df.drop(columns=[c for c in df.columns if str(c).startswith("Unnamed")], inplace=True)

print(f"  Rows    : {len(df):,}")
print(f"  Columns : {len(df.columns)}")

# ── Standardise status to 3 classes ──────────────────────
def norm_status(s):
    if s == "Closed":      return "Closed"
    if s == "In Progress": return "In Progress"
    return "Open"

df["status_3"] = df["status"].apply(norm_status)

# ── 1. Learn: complaint_type → agency (department) ───────
print("\n  Learning: complaint_type → department...")

type_dept = (
    df.groupby("complaint_type")["agency"]
      .agg(lambda x: x.value_counts().index[0])   # most common agency
      .to_dict()
)

# Full agency name map
AGENCY_FULL = {
    "NYPD"  : "NYPD (Police Dept)",
    "HPD"   : "Housing Preservation & Development",
    "DSNY"  : "Sanitation Department",
    "DOT"   : "Department of Transportation",
    "DEP"   : "Department of Environmental Protection",
    "DPR"   : "Parks & Recreation",
    "DOB"   : "Department of Buildings",
    "DOHMH" : "Department of Health & Mental Hygiene",
    "DOE"   : "Department of Education",
    "FDNY"  : "Fire Department",
    "TLC"   : "Taxi & Limousine Commission",
    "EDC"   : "Economic Development Corporation",
    "HRA"   : "Human Resources Administration",
}

type_dept_full = {k: AGENCY_FULL.get(v, v) for k, v in type_dept.items()}
print(f"  Learned {len(type_dept_full)} complaint-type → department mappings")

# ── 2. Learn: complaint_type → status probability ────────
print("\n  Learning: complaint_type → status distribution...")

type_status = {}
for ctype, grp in df.groupby("complaint_type"):
    counts   = grp["status_3"].value_counts()
    total    = len(grp)
    type_status[ctype] = {
        "Closed"      : round(counts.get("Closed",      0) / total * 100, 1),
        "In Progress" : round(counts.get("In Progress", 0) / total * 100, 1),
        "Open"        : round(counts.get("Open",        0) / total * 100, 1),
    }
print(f"  Learned {len(type_status)} complaint-type → status distributions")

# ── 3. Learn: overall status proportions ─────────────────
status_dist = df["status_3"].value_counts(normalize=True).mul(100).round(1).to_dict()
print(f"\n  Overall status distribution:")
for s, p in status_dist.items():
    print(f"    {s:<15} : {p}%")

# ── 4. Top complaint types ────────────────────────────────
top_types = df["complaint_type"].value_counts().head(30).index.tolist()

# ── 5. Borough → most common complaint ───────────────────
borough_top = (
    df.groupby("borough")["complaint_type"]
      .agg(lambda x: x.value_counts().index[0])
      .to_dict()
)

# ── 6. Agency performance (avg status) ───────────────────
agency_stats = {}
for agency, grp in df.groupby("agency"):
    closed_pct = round(grp["status_3"].eq("Closed").mean() * 100, 1)
    agency_stats[agency] = {
        "total"      : len(grp),
        "closed_pct" : closed_pct,
        "full_name"  : AGENCY_FULL.get(agency, agency)
    }

# ── Write learned data as JS module ──────────────────────
print(f"\n  Writing learned data to: {OUT_JS}")

js_content = f"""/**
 * CivicFix ML Model Data
 * ========================
 * AUTO-GENERATED by train_civicfix_model.py
 * Trained on erm2-nwe9.csv  ({len(df):,} records)
 *
 * DO NOT edit manually — run train_civicfix_model.py to regenerate.
 */

// complaint_type → responsible department (learned from dataset)
export const TYPE_TO_DEPT = {json.dumps(type_dept_full, indent=2)};

// complaint_type → status probability distribution (learned from dataset)
export const TYPE_TO_STATUS = {json.dumps(type_status, indent=2)};

// Overall status distribution from dataset
export const STATUS_DIST = {json.dumps(status_dist, indent=2)};

// Top complaint types in dataset
export const TOP_TYPES = {json.dumps(top_types, indent=2)};

// Borough → most common complaint type
export const BOROUGH_TOP_TYPE = {json.dumps(borough_top, indent=2)};

// Agency performance statistics
export const AGENCY_STATS = {json.dumps(agency_stats, indent=2)};

// Dataset metadata
export const DATASET_META = {{
  total_records   : {len(df)},
  total_types     : {df['complaint_type'].nunique()},
  total_agencies  : {df['agency'].nunique()},
  total_boroughs  : {df['borough'].nunique()},
  trained_at      : "{pd.Timestamp.now().strftime('%Y-%m-%d %H:%M')}",
  source_file     : "erm2-nwe9.csv"
}};
"""

with open(OUT_JS, "w", encoding="utf-8") as f:
    f.write(js_content)

print(f"  ✔  Saved: ml_model_data.js")
print("\n" + "=" * 65)
print("  TRAINING COMPLETE")
print("  The web app will now use learned data from your dataset.")
print("=" * 65)
